test('J7: password sign-in protects the app, rejects bad credentials, and signs out', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.goto('/queue')
  await expect(page).toHaveURL(/\/login\?next=%2Fqueue/)
  await expect(page.getByRole('heading', { name: 'Sign in', level: 1 })).toBeVisible()
  await expectAccessible(page, 'login')
  await page.getByLabel('Email').fill('maya.chen@kestrel.example')
  await page.getByLabel('Password', { exact: true }).fill('wrong-password-1')
  await page.getByRole('button', { name: /^Sign in/ }).click()
  await expect(page.getByRole('alert')).toContainText('Email or password is incorrect')
  await page.getByRole('button', { name: /Fill in Maya's account/ }).click()
  await page.getByRole('button', { name: /^Sign in/ }).click()
  await expect(page).toHaveURL(/\/queue/)
  await expect(page.getByRole('heading', { name: 'Exceptions' })).toBeVisible()
  await page.getByRole('button', { name: /Maya Chen/ }).click()
  await expect(page.getByText('password sign-in')).toBeVisible()
  await page.getByRole('menuitem', { name: /Sign out/ }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto('/queue')
  await expect(page).toHaveURL(/\/login/)
})

test('J8: a new user registers, then signs in with the new account', async ({ page }) => {
  const email = `alex.morgan.${Date.now()}@example.com`
  await page.goto('/login')
  await page.getByRole('link', { name: /Create an account/ }).click()
  await expect(page).toHaveURL(/\/register/)
  await expectAccessible(page, 'register')
  await page.getByLabel('Full name').fill('Alex Morgan')
  await page.getByLabel('Work email').fill(email)
  await page.getByText('Austin DC').click()
  await page.getByLabel('Password', { exact: true }).fill('Warehouse-2026')
  await page.getByLabel('Confirm password').fill('Warehouse-2026')
  await page.getByRole('button', { name: /Create account/ }).click()
  await expect(page).toHaveURL(/\/login\?registered=1/)
  await expect(page.getByRole('status')).toContainText('Account created')
  await expect(page.getByLabel('Email')).toHaveValue(email)
  await page.getByLabel('Password', { exact: true }).fill('Warehouse-2026')
  await page.getByRole('button', { name: /^Sign in/ }).click()
  await expect(page).toHaveURL(/\/queue/)
  await expect(page.getByRole('heading', { name: 'Exceptions' })).toBeVisible()
  // The same email cannot register twice.
  await page.getByRole('button', { name: /Account menu for Alex Morgan/ }).click()
  await page.getByRole('menuitem', { name: /Sign out/ }).click()
  await page.goto('/register')
  await page.getByLabel('Full name').fill('Alex Morgan')
  await page.getByLabel('Work email').fill(email)
  await page.getByLabel('Password', { exact: true }).fill('Warehouse-2026')
  await page.getByLabel('Confirm password').fill('Warehouse-2026')
  await page.getByRole('button', { name: /Create account/ }).click()
  await expect(page.getByRole('alert')).toContainText('already exists')
})
